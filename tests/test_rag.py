class TestEmbedder:
    """Tests for embedding generation."""

    def test_hash_embedder(self):
        """Test hash-based embedder."""
        from aero.rag.embedder import HashEmbedder

        embedder = HashEmbedder(dimension=384)

        text = "Test embedding text"
        embedding = embedder.embed(text)

        assert isinstance(embedding, np.ndarray)
        assert embedding.shape == (384,)
        # Should be normalized
        assert abs(np.linalg.norm(embedding) - 1.0) < 0.01

    def test_hash_embedder_deterministic(self):
        """Test that hash embedder is deterministic."""
        from aero.rag.embedder import HashEmbedder

        embedder = HashEmbedder(dimension=384)

        text = "Same text"
        emb1 = embedder.embed(text)
        emb2 = embedder.embed(text)

        np.testing.assert_array_almost_equal(emb1, emb2)

    def test_hash_embedder_different_texts(self):
        """Test that different texts produce different embeddings."""
        from aero.rag.embedder import HashEmbedder

        embedder = HashEmbedder(dimension=384)

        emb1 = embedder.embed("First text")
        emb2 = embedder.embed("Second text completely different")

        # Should not be identical
        assert not np.allclose(emb1, emb2)

    def test_hash_embedder_similarity(self):
        """Test similarity calculation."""
        from aero.rag.embedder import HashEmbedder

        embedder = HashEmbedder(dimension=384)

        # Same text should have similarity 1.0
        sim = embedder.similarity("test", "test")
        assert abs(sim - 1.0) < 0.01

    def test_embed_batch(self):
        """Test batch embedding."""
        from aero.rag.embedder import HashEmbedder

        embedder = HashEmbedder(dimension=384)

        texts = ["First", "Second", "Third"]
        embeddings = embedder.embed_batch(texts)

        assert len(embeddings) == 3
        for emb in embeddings:
            assert isinstance(emb, np.ndarray)
            assert emb.shape == (384,)

    def test_auto_embedder(self):
        """Test auto embedder fallback."""
        from aero.rag.embedder import AutoEmbedder

        embedder = AutoEmbedder()

        # Should work even without Ollama or SentenceTransformers
        embedding = embedder.embed("Test text")

        assert isinstance(embedding, np.ndarray)
        assert len(embedding) > 0


