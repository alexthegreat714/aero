class TestRAGIntegration:
    """Integration tests for the full RAG pipeline."""

    def test_full_pipeline(self, temp_dir, sample_text):
        """Test complete RAG pipeline."""
        from aero.rag.store import create_vector_store
        from aero.rag.embedder import HashEmbedder
        from aero.rag.chunker import TextChunker
        from aero.rag.preprocess import TextPreprocessor

        # Initialize components
        store = create_vector_store(str(temp_dir / "rag.db"))
        embedder = HashEmbedder()
        chunker = TextChunker(chunk_size=200, overlap=40)
        preprocessor = TextPreprocessor()

        # Process document
        processed = preprocessor.preprocess(sample_text)
        cleaned = preprocessor.clean_for_embedding(processed.text)
        chunks = chunker.chunk(cleaned)

        # Create chunk data with embeddings
        chunk_data = [
            {"content": c, "embedding": embedder.embed(c).tolist(), "metadata": {"idx": i}}
            for i, c in enumerate(chunks)
        ]

        # Add to store
        doc_id = store.add_document(
            content=sample_text,
            metadata={"source": "test", "equations": len(processed.equations)},
            chunks=chunk_data,
        )

        assert doc_id is not None
        assert store.count() == 1

        # Search
        query = "Navier-Stokes equations fluid dynamics"
        query_emb = embedder.embed(query)
        results = store.search(query_emb, top_k=3)

        assert len(results) > 0
        # Top result should be relevant
        assert results[0].score > 0

    def test_multiple_documents(self, temp_dir):
        """Test handling multiple documents."""
        from aero.rag.store import create_vector_store
        from aero.rag.embedder import HashEmbedder

        store = create_vector_store(str(temp_dir / "multi.db"))
        embedder = HashEmbedder()

        docs = [
            "Aerodynamics studies air flow around objects like aircraft.",
            "Machine learning uses algorithms to learn patterns from data.",
            "Climate change affects global weather patterns significantly.",
        ]

        for i, content in enumerate(docs):
            chunks = [{"content": content, "embedding": embedder.embed(content).tolist()}]
            store.add_document(content=content, metadata={"doc_num": i}, chunks=chunks)

        assert store.count() == 3

        # Search should find most relevant
        query_emb = embedder.embed("aircraft aerodynamics")
        results = store.search(query_emb, top_k=2)

        assert len(results) == 2
        # First result should be about aerodynamics
        assert "aerodynamics" in results[0].chunk.content.lower() or "air" in results[0].chunk.content.lower()


